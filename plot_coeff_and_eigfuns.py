"""
Plot the local coefficient and the local eigenfunctions of one subdomain.

For every requested store tag the script loads the FNO data generated by
``ex_FNO.py`` from

    <base_path>/<store_tag>/samples_<num_samples>/

namely the local coefficient ``coeff_A_sub_dom_<d>_sample_<s>_nloc_<n>.npy`` of
shape ``(nx_os + 1, ny_os + 1)`` and the local eigenfunctions
``phi_sub_dom_<d>_sample_<s>_nloc_<n>.npy`` of shape
``(nx_os + 1, ny_os + 1, nloc)``.

One figure per store tag: one row per sample, the first column shows the
coefficient, the remaining columns the components of Phi.

Usage
-----
    python plot_coeff_and_eigfuns.py --store_tags channel_rotated_coeff \
        --num_samples 13 [--subdom_idx 5] [--num_plot_samples 5] [--nloc 5]
"""

import argparse
import re
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.colors import LogNorm, TwoSlopeNorm

BASE_PATH = Path("/fs/scratch/rb_bd_dlp_rng_dl01_cr_MSO_employees/students/"
                 "nuj7rng/msgfem_data/fenics_out_data")


def available_samples(data_dir, subdom_idx, nloc):
    """Sample indices for which both coefficient and eigenfunctions exist."""
    pattern = re.compile(rf"^coeff_A_sub_dom_{subdom_idx}_sample_(\d+)_nloc_{nloc}\.npy$")
    indices = []
    for f in data_dir.iterdir():
        m = pattern.match(f.name)
        if m is None:
            continue
        s = int(m.group(1))
        if (data_dir / f"phi_sub_dom_{subdom_idx}_sample_{s}_nloc_{nloc}.npy").exists():
            indices.append(s)
    return sorted(indices)


def subdomain_extent(subdom_idx, Ny, ny, ol, os):
    """Physical extent (x0, x1, y0, y1) of the oversampling domain omega^*."""
    h = 1.0 / ny
    side = 1.0 / Ny
    i, j = subdom_idx % Ny, subdom_idx // Ny
    pad = (ol + os) * h
    return (max(i * side - pad, 0.0), min((i + 1) * side + pad, 1.0),
            max(j * side - pad, 0.0), min((j + 1) * side + pad, 1.0))


def plot_store_tag(store_tag, args):
    data_dir = BASE_PATH / store_tag / f"samples_{args.num_samples}"
    if not data_dir.is_dir():
        raise FileNotFoundError(f"No data directory {data_dir}")

    sample_indices = available_samples(data_dir, args.subdom_idx, args.nloc)
    if not sample_indices:
        raise FileNotFoundError(
            f"No files for subdomain {args.subdom_idx} and nloc {args.nloc} in {data_dir}")
    sample_indices = sample_indices[:args.num_plot_samples]

    coeffs, phis = [], []
    for s in sample_indices:
        coeffs.append(np.load(data_dir / f"coeff_A_sub_dom_{args.subdom_idx}_sample_{s}_nloc_{args.nloc}.npy"))
        phis.append(np.load(data_dir / f"phi_sub_dom_{args.subdom_idx}_sample_{s}_nloc_{args.nloc}.npy"))

    n_components = phis[0].shape[2]
    n_rows, n_cols = len(sample_indices), 1 + n_components
    extent = subdomain_extent(args.subdom_idx, args.Ny, args.ny, args.ol, args.os)

    fig, axes = plt.subplots(n_rows, n_cols,
                             figsize=(2.9 * n_cols, 3.0 * n_rows),
                             squeeze=False)
    for r, s in enumerate(sample_indices):
        A, phi = coeffs[r], phis[r]

        ax = axes[r][0]
        # Arrays are indexed [ix, iy]; transpose so that x is horizontal.
        im = ax.imshow(A.T, origin="lower", extent=extent, cmap="viridis",
                       norm=LogNorm(vmin=A.min(), vmax=A.max()))
        ax.set_title(fr"$A_{{\xi_{{{s}}}}}$, contrast $={A.max() / A.min():.2f}$",
                     fontsize=9)
        fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)

        for k in range(n_components):
            ax = axes[r][k + 1]
            z = phi[:, :, k]
            vmax = np.abs(z).max()
            im = ax.imshow(z.T, origin="lower", extent=extent, cmap="RdBu_r",
                           norm=TwoSlopeNorm(vmin=-vmax, vcenter=0.0, vmax=vmax))
            ax.set_title(fr"$\Phi_{{\xi_{{{s}}}}}^{{{k}}}$", fontsize=9)
            fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)

        for ax in axes[r]:
            ax.set_xlabel(r"$x$", fontsize=8)
            ax.tick_params(labelsize=7)
        axes[r][0].set_ylabel(r"$y$", fontsize=8)

    fig.suptitle(f"{store_tag} — subdomain {args.subdom_idx}", fontsize=13)
    fig.tight_layout(rect=(0, 0, 1, 0.97))

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    out_file = out_dir / f"{store_tag}_sub_dom_{args.subdom_idx}_nloc_{args.nloc}_coeff_and_eigfuns.png"
    fig.savefig(out_file, dpi=170, bbox_inches="tight")
    plt.close(fig)
    print(f"Saved {out_file}  (samples {sample_indices})")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--store_tags", type=str, nargs="+", required=True,
                        help="store tags to plot; one figure per tag")
    parser.add_argument("--num_samples", type=int, required=True,
                        help="selects the directory samples_<num_samples>")
    parser.add_argument("--subdom_idx", type=int, default=5,
                        help="index of the subdomain to plot")
    parser.add_argument("--num_plot_samples", type=int, default=5,
                        help="number of samples to plot from the selection")
    parser.add_argument("--nloc", type=int, default=5,
                        help="nloc tag of the stored files")
    parser.add_argument("--Ny", type=int, default=4, help="coarse cells per direction")
    parser.add_argument("--ny", type=int, default=2 ** 8, help="fine cells per direction")
    parser.add_argument("--ol", type=int, default=2, help="overlap in fine cells")
    parser.add_argument("--os", type=int, default=2, help="oversampling in fine cells")
    parser.add_argument("--out_dir", type=str, default="plots/coeff_and_eigfuns",
                        help="directory in which the figures are stored")
    args = parser.parse_args()

    for store_tag in args.store_tags:
        plot_store_tag(store_tag, args)


if __name__ == "__main__":
    main()
